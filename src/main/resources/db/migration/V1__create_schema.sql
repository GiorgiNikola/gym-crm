-- The schema Hibernate used to generate from the entities. Written to run on PostgreSQL and on
-- H2 in PostgreSQL mode, so the tests validate the entities against these exact tables.

create table users (
    id         bigint       generated by default as identity,
    first_name varchar(50)  not null,
    last_name  varchar(50)  not null,
    username   varchar(120) not null unique,
    password   varchar(100) not null,
    is_active  boolean      not null,
    primary key (id)
);

create table training_types (
    id   bigint      generated by default as identity,
    name varchar(50) not null unique,
    primary key (id)
);

create table trainees (
    id            bigint generated by default as identity,
    user_id       bigint not null unique,
    date_of_birth date,
    address       varchar(255),
    primary key (id),
    constraint fk_trainees_user foreign key (user_id) references users
);

create table trainers (
    id                bigint generated by default as identity,
    user_id           bigint not null unique,
    specialization_id bigint not null,
    primary key (id),
    constraint fk_trainers_user foreign key (user_id) references users,
    constraint fk_trainers_specialization foreign key (specialization_id) references training_types
);

create table trainings (
    id               bigint       generated by default as identity,
    trainee_id       bigint       not null,
    trainer_id       bigint       not null,
    training_type_id bigint       not null,
    name             varchar(100) not null,
    date             date         not null,
    duration         bigint       not null,
    primary key (id),
    constraint fk_trainings_trainee foreign key (trainee_id) references trainees,
    constraint fk_trainings_trainer foreign key (trainer_id) references trainers,
    constraint fk_trainings_type foreign key (training_type_id) references training_types
);

create table trainee2trainer (
    trainee_id bigint not null,
    trainer_id bigint not null,
    primary key (trainee_id, trainer_id),
    constraint fk_trainee2trainer_trainee foreign key (trainee_id) references trainees,
    constraint fk_trainee2trainer_trainer foreign key (trainer_id) references trainers
);
